import { contrastRatio } from './color.mjs';
import { evaluateContrast } from './contrast-pairs.mjs';
import { STATUSES, cssVarName, kebab } from './model.mjs';

const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
const v = (...path) => `var(${cssVarName(path)})`;

export function previewHtml(m, css, version) {
  const L = m.themes.light.colorsFlat;
  const D = m.themes.dark.colorsFlat;
  const results = evaluateContrast({ light: L, dark: D }, contrastRatio);
  const failures = results.filter((r) => !r.pass).length;

  const palette = Object.entries(m.palette)
    .filter(([, s]) => typeof s === 'object')
    .map(
      ([g, scale]) => `<div class="row"><div class="row-label">${g}</div><div class="ramp">${Object.entries(scale)
        .map(([k, hex]) => {
          const onDark = contrastRatio(hex, '#FFFFFF') >= contrastRatio(hex, '#0D0F14');
          return `<div class="chip" style="background:${hex};color:${onDark ? '#fff' : '#0D0F14'}"><b>${k}</b><span>${hex}</span></div>`;
        })
        .join('')}</div></div>`,
    )
    .join('');

  const groups = {};
  for (const role of Object.keys(L)) (groups[role.split('.').slice(0, role.startsWith('status') ? 2 : 1).join('.')] ??= []).push(role);
  const semantic = Object.entries(groups)
    .map(
      ([g, roles]) => `<div class="sem-group"><h4>${g}</h4><div class="sem-grid">${roles
        .map(
          (r) => `<div class="sem"><div class="sem-swatch" style="background:${v('color', ...r.split('.'))}"></div><div><code>${esc(cssVarName(['color', ...r.split('.')]))}</code><small><span class="only-light">${L[r]}</span><span class="only-dark">${D[r]}</span></small></div></div>`,
        )
        .join('')}</div></div>`,
    )
    .join('');

  const statusRows = STATUSES.map((s) => {
    const c = (k) => v('color', 'status', s, k);
    return `<div class="status-row">
      <span class="badge" style="background:${c('subtle')};color:${c('fg')};border-color:${c('border')}"><i class="dot${s === 'running' ? ' pulse' : ''}" style="background:${c('solid')}"></i>${s}</span>
      <span class="badge solid" style="background:${c('solid')};color:${c('onSolid')}">${s}</span>
      <span class="status-text" style="color:${c('fg')}">Run #42 is ${s}</span>
    </div>`;
  }).join('');

  const type = Object.entries(m.typography)
    .map(([k, t]) => `<div class="type-row"><div class="type-meta"><code>.side-text-${kebab(k)}</code><small>${t.fontSize}/${t.lineHeight} · ${t.fontWeight}</small></div><div class="side-text-${kebab(k)}">${k === 'code' ? 'env.step(&quot;click(\'a51\')&quot;)' : 'Watch agents browse, live.'}</div></div>`)
    .join('');

  const space = Object.entries(m.space)
    .map(([k, px]) => `<div class="space-row"><code>${k}</code><div class="space-bar" style="width:${v('space', k)}"></div><small>${px}px</small></div>`)
    .join('');
  const radii = Object.entries(m.radius)
    .map(([k, px]) => `<div class="radius-box" style="border-radius:${v('radius', k)}"><code>${k}</code><small>${px === 9999 ? 'full' : `${px}px`}</small></div>`)
    .join('');
  const shadows = Object.keys(m.themes.light.shadows)
    .map((k) => `<div class="shadow-box" style="box-shadow:${v('shadow', k)}"><code>shadow-${k}</code></div>`)
    .join('');
  const motion = Object.entries(m.easing)
    .map(([k]) => `<div class="motion-row"><code>${k}</code><div class="track"><div class="ball" style="transition-timing-function:${v('motion', 'easing', k)}"></div></div></div>`)
    .join('');
  const durations = Object.entries(m.duration).map(([k, ms]) => `<code>${k} ${ms}ms</code>`).join(' ');

  const contrastTable = ['light', 'dark']
    .map(
      (theme) => `<div class="contrast-col"><h4>${theme}</h4><table><thead><tr><th>pair</th><th>ratio</th><th>min</th><th></th></tr></thead><tbody>${results
        .filter((r) => r.theme === theme)
        .map(
          (r) => `<tr><td><span class="mini" style="background:${r.bgHex};color:${r.fgHex}">Aa</span> ${esc(r.fg)} <span class="on">on</span> ${esc(r.bg)}</td><td>${r.ratio.toFixed(2)}</td><td>${r.min}</td><td class="${r.pass ? 'ok' : 'bad'}">${r.pass ? 'AA' : 'FAIL'}</td></tr>`,
        )
        .join('')}</tbody></table></div>`,
    )
    .join('');

  return `<!doctype html>
<!-- Generated by @side/design-tokens build. Do not edit by hand. -->
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Side design tokens v${version}</title>
<style>
${css}
/* ---- preview page chrome (uses only Side tokens) ---- */
*{box-sizing:border-box}
body{margin:0;background:${v('color', 'bg', 'canvas')};color:${v('color', 'fg', 'default')};font-family:${v('font', 'family', 'sans')};font-size:${v('font', 'size', 'sm')};line-height:${v('font', 'line-height', 'sm')};transition:background ${v('motion', 'duration', 'base')} ${v('motion', 'easing', 'standard')}}
header{position:sticky;top:0;z-index:2;display:flex;align-items:center;gap:${v('space', 'md')};padding:${v('space', 'md')} ${v('space', 'xl')};background:${v('color', 'bg', 'surface')};border-bottom:${v('border-width', 'hairline')} solid ${v('color', 'border', 'default')}}
.logo{width:32px;height:32px;border-radius:${v('radius', 'md')};background:linear-gradient(135deg,${v('color', 'brand', '500')},${v('color', 'accent', '400')});display:grid;place-items:center;color:#fff;font-weight:700}
header h1{margin:0}
header .spacer{flex:1}
main{max-width:1200px;margin:0 auto;padding:${v('space', 'xl')};display:grid;gap:${v('space', 'lg')}}
section{background:${v('color', 'bg', 'surface')};border:${v('border-width', 'hairline')} solid ${v('color', 'border', 'default')};border-radius:${v('radius', 'lg')};padding:${v('space', 'lg')};box-shadow:${v('shadow', 'sm')}}
section>h2{margin:0 0 ${v('space', 'md')}}
h4{margin:${v('space', 'md')} 0 ${v('space', 'xs')};color:${v('color', 'fg', 'muted')};font-size:${v('font', 'size', 'xs')};text-transform:uppercase;letter-spacing:${v('font', 'letter-spacing', 'wide')}}
code{font-family:${v('font', 'family', 'mono')};font-size:${v('font', 'size', 'xs')}}
small{display:block;color:${v('color', 'fg', 'muted')};font-size:${v('font', 'size', 'xs')}}
.muted{color:${v('color', 'fg', 'muted')}}
.btn{font:inherit;font-weight:600;border:0;cursor:pointer;padding:${v('space', 'xs')} ${v('space', 'md')};border-radius:${v('radius', 'md')};transition:background ${v('motion', 'duration', 'fast')} ${v('motion', 'easing', 'standard')}}
.btn:focus-visible{outline:${v('border-width', 'thick')} solid ${v('color', 'border', 'focus')};outline-offset:2px}
.btn.primary{background:${v('color', 'primary', 'solid')};color:${v('color', 'primary', 'on-solid')}}.btn.primary:hover{background:${v('color', 'primary', 'solid-hover')}}
.btn.accent{background:${v('color', 'accent', 'solid')};color:${v('color', 'accent', 'on-solid')}}.btn.accent:hover{background:${v('color', 'accent', 'solid-hover')}}
.btn.secondary{background:${v('color', 'bg', 'surface')};color:${v('color', 'fg', 'default')};box-shadow:inset 0 0 0 1px ${v('color', 'border', 'strong')}}
.btn.ghost{background:${v('color', 'primary', 'subtle')};color:${v('color', 'primary', 'fg')}}
.row{display:flex;align-items:center;gap:${v('space', 'sm')};margin-bottom:${v('space', 'xs')}}
.row-label{width:64px;font-weight:600}
.ramp{display:grid;grid-template-columns:repeat(13,1fr);gap:4px;flex:1}
.chip{border-radius:${v('radius', 'sm')};padding:${v('space', 'xs')} 6px;min-height:52px;display:flex;flex-direction:column;justify-content:space-between;font-size:10px}
.chip span{font-family:${v('font', 'family', 'mono')};opacity:.9}
.sem-grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(250px,1fr));gap:${v('space', 'xs')}}
.sem{display:flex;gap:${v('space', 'xs')};align-items:center}
.sem-swatch{width:36px;height:36px;border-radius:${v('radius', 'md')};border:1px solid ${v('color', 'border', 'default')};flex:none}
.only-dark{display:none}[data-theme="dark"] .only-dark{display:inline}[data-theme="dark"] .only-light{display:none}
.status-row{display:flex;gap:${v('space', 'md')};align-items:center;padding:${v('space', 'xs')} 0;border-bottom:1px solid ${v('color', 'border', 'default')}}
.badge{display:inline-flex;align-items:center;gap:6px;padding:2px 10px;border-radius:${v('radius', 'full')};border:1px solid transparent;font-weight:500;font-size:${v('font', 'size', 'xs')};line-height:${v('font', 'line-height', 'sm')};min-width:110px;text-transform:capitalize}
.badge.solid{justify-content:center}
.dot{width:8px;height:8px;border-radius:50%;display:inline-block}
.pulse{animation:pulse 1.2s ${v('motion', 'easing', 'standard')} infinite}
@keyframes pulse{50%{opacity:.35}}
.status-text{font-weight:500}
.type-row{display:grid;grid-template-columns:220px 1fr;gap:${v('space', 'md')};align-items:baseline;padding:${v('space', 'xs')} 0;border-bottom:1px solid ${v('color', 'border', 'default')}}
.grid2{display:grid;grid-template-columns:1fr 1fr;gap:${v('space', 'lg')}}
.space-row{display:grid;grid-template-columns:48px 1fr 48px;gap:${v('space', 'xs')};align-items:center;margin:4px 0}
.space-bar{height:12px;background:${v('color', 'primary', 'solid')};border-radius:2px}
.radii,.shadows{display:flex;flex-wrap:wrap;gap:${v('space', 'md')}}
.radius-box{width:84px;height:84px;background:${v('color', 'primary', 'subtle')};border:1px solid ${v('color', 'primary', 'border')};display:grid;place-content:center;text-align:center}
.shadow-box{width:160px;height:84px;border-radius:${v('radius', 'lg')};background:${v('color', 'bg', 'surface')};display:grid;place-items:center}
.shadows{padding:${v('space', 'md')};background:${v('color', 'bg', 'canvas')};border-radius:${v('radius', 'md')}}
.motion-row{display:grid;grid-template-columns:96px 1fr;align-items:center;gap:${v('space', 'xs')};margin:6px 0}
.track{height:20px;background:${v('color', 'bg', 'subtle')};border-radius:${v('radius', 'full')};position:relative}
.ball{position:absolute;left:2px;top:2px;width:16px;height:16px;border-radius:50%;background:${v('color', 'accent', 'solid')};transition-property:left;transition-duration:${v('motion', 'duration', 'slower')}}
#motion:hover .ball{left:calc(100% - 18px)}
.contrast{display:grid;grid-template-columns:1fr 1fr;gap:${v('space', 'lg')}}
table{width:100%;border-collapse:collapse;font-size:${v('font', 'size', 'xs')}}
td,th{text-align:left;padding:3px 6px;border-bottom:1px solid ${v('color', 'border', 'default')}}
.mini{display:inline-block;padding:0 4px;border-radius:3px;font-weight:600;border:1px solid ${v('color', 'border', 'default')}}
.on{color:${v('color', 'fg', 'muted')}}
.ok{color:${v('color', 'status', 'succeeded', 'fg')};font-weight:700}.bad{color:${v('color', 'status', 'failed', 'fg')};font-weight:700}
.summary{display:inline-flex;gap:6px;align-items:center}
</style>
</head>
<body>
<header>
  <div class="logo">S</div>
  <div><h1 class="side-text-title">Side design tokens</h1><small>v${version} · generated from tokens/ by Style Dictionary</small></div>
  <div class="spacer"></div>
  <span class="badge" style="background:${v('color', 'status', failures ? 'failed' : 'succeeded', 'subtle')};color:${v('color', 'status', failures ? 'failed' : 'succeeded', 'fg')};border-color:${v('color', 'status', failures ? 'failed' : 'succeeded', 'border')}">WCAG AA: ${results.length - failures}/${results.length} pairs pass</span>
  <button class="btn secondary" id="toggle" type="button">Toggle theme</button>
</header>
<main>
  <section>
    <h2 class="side-text-h3">Run status</h2>
    <p class="muted">Matches <code>RunStatus</code> in contracts/openapi.yaml: queued · running · succeeded · failed · cancelled.</p>
    ${statusRows}
  </section>
  <section>
    <h2 class="side-text-h3">Actions</h2>
    <div class="row" style="gap:12px"><button class="btn primary">Launch run</button><button class="btn accent">Replay trace</button><button class="btn secondary">Cancel</button><button class="btn ghost">View steps</button><a href="#" style="color:${v('color', 'primary', 'fg')}">Open in BrowserGym →</a></div>
  </section>
  <section>
    <h2 class="side-text-h3">Semantic colours <small style="display:inline">(theme-aware CSS variables)</small></h2>
    ${semantic}
  </section>
  <section>
    <h2 class="side-text-h3">Palette</h2>
    ${palette}
  </section>
  <section>
    <h2 class="side-text-h3">Typography</h2>
    ${type}
  </section>
  <div class="grid2">
    <section><h2 class="side-text-h3">Spacing</h2>${space}</section>
    <section><h2 class="side-text-h3">Radii</h2><div class="radii">${radii}</div><h4>Shadows</h4><div class="shadows">${shadows}</div></section>
  </div>
  <section id="motion">
    <h2 class="side-text-h3">Motion <small style="display:inline">(hover to play)</small></h2>
    <p class="muted">Durations: ${durations}</p>
    ${motion}
  </section>
  <section>
    <h2 class="side-text-h3">Contrast (WCAG 2.1 AA)</h2>
    <p class="muted">Text pairs need ≥ 4.5:1, UI components / graphics ≥ 3:1. Enforced by <code>npm test</code>.</p>
    <div class="contrast">${contrastTable}</div>
  </section>
</main>
<script>
  const root = document.documentElement;
  const q = new URLSearchParams(location.search).get('theme');
  const initial = q || (matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light');
  root.dataset.theme = initial;
  document.getElementById('toggle').onclick = () => { root.dataset.theme = root.dataset.theme === 'dark' ? 'light' : 'dark'; };
</script>
</body>
</html>
`;
}
