export function tailwindV4Css(m) {
  const lines = [];
  for (const [g, scale] of Object.entries(m.palette)) {
    if (typeof scale === 'string') lines.push(`--color-${g}: ${scale};`);
    else for (const [k, v] of Object.entries(scale)) lines.push(`--color-${g}-${k}: ${v};`);
  }
  lines.push(`--font-sans: ${m.font.family.sans};`, `--font-mono: ${m.font.family.mono};`);
  for (const [k, v] of Object.entries(m.font.size)) lines.push(`--text-${k}: ${rem(v)};`, `--text-${k}--line-height: ${rem(m.font.lineHeight[k])};`);
  for (const [k, v] of Object.entries(m.space)) lines.push(`--spacing-${k}: ${rem(v)};`);
  for (const [k, v] of Object.entries(m.radius)) lines.push(`--radius-${k}: ${px(v)};`);
  for (const [k, v] of Object.entries(m.easing)) lines.push(`--ease-${k}: ${bezier(v)};`);
  const inline = [];
  for (const role of Object.keys(m.themes.light.colorsFlat)) {
    const parts = role.split('.');
    inline.push(`--color-${parts.map(kebab).join('-')}: var(${cssVarName(['color', ...parts])});`);
  }
  for (const k of Object.keys(m.themes.light.shadows)) inline.push(`--shadow-${k}: var(${cssVarName(['shadow', k])});`);
  return `/* ${HEADER}\n * Tailwind CSS v4: @import "tailwindcss"; @import "@side/design-tokens/css"; @import "@side/design-tokens/tailwind/theme.css"; */\n\n${block('@theme', lines)}\n\n${block('@theme inline', inline)}\n`;
}

// ---------- React Native ----------

function nativeShadow(layers) {
  const l = layers[0];
  return {
    shadowColor: l.color,
    shadowOffset: { width: l.offsetX, height: l.offsetY },
    shadowOpacity: l.opacity,
    shadowRadius: l.blur / 2,
    elevation: Math.max(1, Math.round(l.offsetY * 1.5)),
  };
}

export function nativeTheme(m, mode) {
  const family = (f) => (f === m.font.family.mono ? m.font.nativeFamily.mono : m.font.nativeFamily.sans);
  return {
    mode,
    colors: m.themes[mode].colors,
    palette: m.palette,
    space: m.space,
    radius: m.radius,
    borderWidth: m.borderWidth,
    fontFamily: { sans: m.font.nativeFamily.sans, mono: m.font.nativeFamily.mono },
    fontSize: m.font.size,
    lineHeight: m.font.lineHeight,
    fontWeight: Object.fromEntries(Object.entries(m.font.weight).map(([k, v]) => [k, String(v)])),
    textStyles: Object.fromEntries(
      Object.entries(m.typography).map(([k, v]) => [
        k,
        {
          fontFamily: family(v.fontFamily),
          fontSize: v.fontSize,
          lineHeight: v.lineHeight,
          fontWeight: String(v.fontWeight),
          letterSpacing: +(v.letterSpacing * v.fontSize).toFixed(2),
        },
      ]),
    ),
    shadows: Object.fromEntries(Object.entries(m.themes[mode].shadows).map(([k, v]) => [k, nativeShadow(v)])),
    motion: { duration: m.duration, easing: m.easing },
  };
}

function tsType(value, key, indent = '') {
  if (key === 'mode') return 'ColorSchemeName';
  if (typeof value === 'string') return /^(fontWeight|regular|medium|semibold|bold)$/.test(key) && /^[1-9]00$/.test(value) ? 'FontWeight' : 'string';
  if (typeof value === 'number') return 'number';
  if (Array.isArray(value)) return `readonly [${value.map(() => 'number').join(', ')}]`;
  const inner = Object.entries(value)
    .map(([k, v]) => `${indent}  readonly ${/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k)}: ${tsType(v, k, indent + '  ')};`)
    .join('\n');
  return `{\n${inner}\n${indent}}`;
}

export function nativeFormat(m) {
  const light = nativeTheme(m, 'light');
  const dark = nativeTheme(m, 'dark');
  const lit = (o) => JSON.stringify(o, null, 2);
  return `/* ${HEADER} */
/* React Native / Expo theme. Usage: const theme = getTheme(useColorScheme()); */

export type ColorSchemeName = 'light' | 'dark';
export type FontWeight = '100' | '200' | '300' | '400' | '500' | '600' | '700' | '800' | '900';
export type RunStatus = ${STATUSES.map((s) => `'${s}'`).join(' | ')};

export type SideTheme = ${tsType(light, '')};

export const lightTheme: SideTheme = ${lit(light)};

export const darkTheme: SideTheme = ${lit(dark)};

export const themes: Record<ColorSchemeName, SideTheme> = { light: lightTheme, dark: darkTheme };

export function getTheme(scheme?: string | null): SideTheme {
  return scheme === 'dark' ? darkTheme : lightTheme;
}

export function statusColors(theme: SideTheme, status: RunStatus): SideTheme['colors']['status'][RunStatus] {
  return theme.colors.status[status];
}

export default themes;
`;
}

// ---------- JSON ----------

export function jsonFormat(m, version) {
  const themes = Object.fromEntries(
    Object.entries(m.themes).map(([k, t]) => [k, { color: t.colors, shadow: t.shadows }]),
  );
  const contrast = evaluateContrast(
    Object.fromEntries(Object.entries(m.themes).map(([k, t]) => [k, t.colorsFlat])),
    contrastRatio,
  ).map((r) => ({ theme: r.theme, fg: r.fg, bg: r.bg, ratio: +r.ratio.toFixed(2), min: r.min, pass: r.pass }));
  return `${JSON.stringify({ $meta: { name: '@side/design-tokens', version, note: HEADER }, base: m.nestedBase, themes, contrast }, null, 2)}\n`;
}

export function jsonFlatFormat(m) {
  return `${JSON.stringify(Object.fromEntries(m.tokens.map((t) => [t.path.join('.'), t.value])), null, 2)}\n`;
}
