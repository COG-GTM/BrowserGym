const HEADER = 'Generated by @side/design-tokens (Style Dictionary). Do not edit by hand; edit tokens/ and run `npm run build`.';

// ---------- CSS ----------

export function shadowCss(layers) {
  return layers
    .map((l) => `${px(l.offsetX)} ${px(l.offsetY)} ${px(l.blur)} ${px(l.spread)} ${rgba(l.color, l.opacity)}`)
    .join(', ');
}

function baseCssValue(t) {
  switch (t.type) {
    case 'fontSize':
    case 'lineHeight':
      return rem(t.value);
    case 'dimension':
      return t.path[0] === 'space' ? rem(t.value) : px(t.value);
    case 'letterSpacing':
      return t.value === 0 ? '0' : `${t.value}em`;
    case 'duration':
      return `${t.value}ms`;
    case 'cubicBezier':
      return bezier(t.value);
    default:
      return String(t.value);
  }
}

function themeDecls(theme) {
  const lines = [];
  for (const [role, hex] of Object.entries(theme.colorsFlat)) {
    const name = cssVarName(['color', ...role.split('.')]);
    lines.push(`${name}: ${hex};`, `${name}-rgb: ${rgbChannels(hex)};`);
  }
  for (const [name, layers] of Object.entries(theme.shadows)) lines.push(`${cssVarName(['shadow', name])}: ${shadowCss(layers)};`);
  return lines;
}

const block = (selector, lines, indent = '') =>
  `${indent}${selector} {\n${lines.map((l) => `${indent}  ${l}`).join('\n')}\n${indent}}`;

export function cssFormat(m) {
  const baseLines = [];
  for (const t of m.base) {
    if (t.type === 'typography') {
      for (const [k, v] of Object.entries(t.value)) {
        const val = k === 'fontFamily' || k === 'fontWeight' ? v : k === 'letterSpacing' ? (v === 0 ? '0' : `${v}em`) : rem(v);
        baseLines.push(`${cssVarName([...t.path, k])}: ${val};`);
      }
    } else if (!(t.path[0] === 'font' && t.path[2] === 'native')) {
      baseLines.push(`${cssVarName(t.path)}: ${baseCssValue(t)};`);
    }
  }
  const light = themeDecls(m.themes.light);
  const dark = themeDecls(m.themes.dark);
  const textClasses = Object.keys(m.typography).map((name) => {
    const v = (k) => `var(${cssVarName(['typography', name, k])})`;
    return block(`.side-text-${kebab(name)}`, [
      `font-family: ${v('fontFamily')};`,
      `font-size: ${v('fontSize')};`,
      `line-height: ${v('lineHeight')};`,
      `font-weight: ${v('fontWeight')};`,
      `letter-spacing: ${v('letterSpacing')};`,
    ]);
  });
  return [
    `/* ${HEADER}\n * Theme: light by default, dark via prefers-color-scheme or [data-theme="dark"] (force light with [data-theme="light"]). */`,
    block(':root', [...baseLines, 'color-scheme: light;', ...light]),
    `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="light"])', ['color-scheme: dark;', ...dark], '  ')}\n}`,
    block('[data-theme="dark"]', ['color-scheme: dark;', ...dark]),
    block('[data-theme="light"]', ['color-scheme: light;', ...light]),
    ...textClasses,
  ].join('\n\n') + '\n';
}

// ---------- Tailwind ----------

function semanticTailwindColors(theme) {
  const out = {};
  const walk = (obj, path, target) => {
    for (const [k, v] of Object.entries(obj)) {
      const key = kebab(k);
      if (typeof v === 'string') target[key] = `rgb(var(${cssVarName(['color', ...path, k])}-rgb) / <alpha-value>)`;
      else walk(v, [...path, k], (target[key] ??= {}));
    }
  };
  walk(theme.colors, [], out);
  return out;
}

export function tailwindTheme(m) {
  const colors = { white: m.palette.white, black: m.palette.black };
  for (const [g, scale] of Object.entries(m.palette)) if (typeof scale === 'object') colors[g] = { ...scale };
  for (const [g, v] of Object.entries(semanticTailwindColors(m.themes.light))) colors[g] = { ...(colors[g] ?? {}), ...v };
  const mapObj = (o, f) => Object.fromEntries(Object.entries(o).map(([k, v]) => [k, f(v, k)]));
  const splitStack = (s) => s.split(/,\s*/).map((x) => x.replace(/^"|"$/g, ''));
  return {
    darkMode: ['selector', '[data-theme="dark"]'],
    theme: {
      extend: {
        colors,
        fontFamily: { sans: splitStack(m.font.family.sans), mono: splitStack(m.font.family.mono) },
        fontSize: mapObj(m.font.size, (v, k) => [rem(v), { lineHeight: rem(m.font.lineHeight[k]) }]),
        fontWeight: mapObj(m.font.weight, String),
        letterSpacing: mapObj(m.font.letterSpacing, (v) => (v === 0 ? '0' : `${v}em`)),
        spacing: mapObj(m.space, rem),
        borderRadius: mapObj(m.radius, px),
        borderWidth: mapObj(m.borderWidth, px),
        boxShadow: mapObj(m.themes.light.shadows, (_, k) => `var(${cssVarName(['shadow', k])})`),
        transitionDuration: mapObj(m.duration, (v) => `${v}ms`),
        transitionTimingFunction: mapObj(m.easing, bezier),
      },
    },
  };
}

